import { mkdtemp, readdir, rm, mkdir, copyFile, access, readFile, writeFile } from 'node:fs/promises';
import { constants as fsConstants } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { spawn } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const ROOT_DIR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SVG_SOURCE_DIR = path.join(ROOT_DIR, 'web', 'src', 'assets', 'svg');
const SVG_EXCLUDE_DIR = path.join(SVG_SOURCE_DIR, 'animated');
const FONT_OUTPUT_DIR = path.join(ROOT_DIR, 'web', 'src', 'assets', 'fonts');
const FONT_NAME = 'opdevtools-icons';
const FONT_WOFF_FILE = `${FONT_NAME}.woff`;
const FONT_PREVIEW_FILE = `${FONT_NAME}-preview.html`;
const FONT_CSS_FILE = `${FONT_NAME}.css`;

